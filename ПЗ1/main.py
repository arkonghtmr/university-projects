import math


def f(x):
    """
    Левая функция (Вариант 25): 1 / (x^2 - 9).
    Определена везде, кроме x = 3 и x = -3.
    """
    return 1 / (x ** 2 - 9)


def g(x):
    """
    Правая функция (Вариант 25): sqrt(x + 15).
    Определена при x >= -15.
    """
    return math.sqrt(x + 15)


def task_function(x, n):
    """
    Вычисляет значение составной функции.

    Логика:
    - Если x < n, используется f(x).
    - Если x >= n, используется формула стыковки: g(x) - g(n) + f(n).

    Аргументы:
    x -- аргумент функции (число)
    n -- граница переключения (число)

    Примеры (doctest):

    1. Проверка левой ветви (x < n):
       Пусть n=5, x=0. f(0) = 1/(0-9) = -0.111...
    >>> task_function(0, 5)
    -0.1111111111111111

    2. Проверка правой ветви (x >= n) со стыковкой:
       Пусть n=4, x=4. Должно быть равно f(4).
       f(4) = 1/(16-9) = 1/7 ≈ 0.142857
    >>> round(task_function(4, 4), 6)
    0.142857

    3. Проверка деления на ноль (x=3 при n > 3):
    >>> task_function(3, 5)
    Traceback (most recent call last):
        ...
    ZeroDivisionError: division by zero
    """
    if x < n:
        return f(x)
    else:
        # Формула стыковки: сдвигаем g(x) так, чтобы в точке n она совпала с f(n)
        return g(x) - g(n) + f(n)


